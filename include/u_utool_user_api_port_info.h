	uint8_t port_mode_en : 1;
	uint8_t dl_link : 1;
	uint8_t phy_link : 1;
	uint8_t cur_port_type : 1;
	uint8_t reserved_0 : 1;
	uint8_t mac_lstm;
	uint32_t decoded_fail_block_num;
	uint32_t fec_err_low;
	uint32_t retry_cnt;
	uint32_t dl_link_fsm;
	uint32_t fec_err_high;
